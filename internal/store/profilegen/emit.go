package profilegen

import (
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"

	"github.com/klauspost/compress/zstd"
)

// GoSource emits a complete precomputed profile as ordinary Go declarations.
// JSON map ordering, single-threaded compression, and fixed line wrapping keep
// the output independent of host paths, clocks, and map iteration order.
func (r *Result) GoSource(ctx context.Context, plugin []byte) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("encode Store profile: %w", err)
	}

	if r == nil || r.Profile == nil || r.Profile.UUID != FrameworkUUID || r.Profile.PluginUUID != PluginUUID {
		return nil, fmt.Errorf("profile does not match pinned Apple images")
	}

	if len(r.Pages) == 0 || len(r.Pages)%4096 != 0 || len(r.Profile.Pages) != len(r.Pages)/4096 || len(plugin) == 0 {
		return nil, fmt.Errorf("incomplete profile output")
	}

	for i, page := range r.Profile.Pages {
		if page.Address%4096 != 0 || page.Offset != uint64(i)*4096 {
			return nil, fmt.Errorf("invalid profile page index")
		}
	}

	metadata, err := json.Marshal(r.Profile)
	if err != nil {
		return nil, fmt.Errorf("encode profile metadata: %w", err)
	}

	encoder, err := zstd.NewWriter(nil, zstd.WithEncoderLevel(zstd.SpeedBestCompression), zstd.WithEncoderConcurrency(1), zstd.WithEncoderCRC(true))
	if err != nil {
		return nil, fmt.Errorf("create profile encoder: %w", err)
	}

	defer encoder.Close()

	var source strings.Builder

	source.WriteString("// Code generated by go run ./internal/store/profilegen/cmd/profilegen; DO NOT EDIT.\n")
	fmt.Fprintf(&source, "// Pinned inputs: %s\n\npackage profile\n\n", Version())
	fmt.Fprintf(&source, "const generatedFrameworkUUID = %q\nconst generatedPluginUUID = %q\n\n", FrameworkUUID, PluginUUID)

	for _, part := range []struct {
		identifier, name string
		data             []byte
	}{{"generatedMetadata", "Store metadata", metadata}, {"generatedPages", "Store pages", r.Pages}, {"generatedPlugin", "Store authentication plugin", plugin}} {
		if err := ctx.Err(); err != nil {
			return nil, fmt.Errorf("encode Store profile: %w", err)
		}

		encoded := base64.StdEncoding.EncodeToString(encoder.EncodeAll(part.data, nil))
		fmt.Fprintf(&source, "var %s = artifact{\nName: %q,\nSize: %d,\nSHA256: %q,\nEncoded: `\n", part.identifier, part.name, len(part.data), digest(part.data))

		for start := 0; start < len(encoded); start += 120 {
			source.WriteString(encoded[start:min(start+120, len(encoded))])
			source.WriteByte('\n')
		}

		source.WriteString("`,\n}\n\n")
	}

	result, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated profile: %w", err)
	}

	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("encode Store profile: %w", err)
	}

	return result, nil
}
